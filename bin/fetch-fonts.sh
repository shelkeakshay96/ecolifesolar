#!/usr/bin/env bash
#
# Downloads the three Eco Life webfonts from Google Fonts and self-hosts them.
#
# The site sends "Content-Security-Policy: default-src 'self'", so a stylesheet
# from fonts.googleapis.com and font files from fonts.gstatic.com are both
# blocked at render time. The original static site linked to Google's CDN; here
# the files are fetched once, committed, and served from our own origin.
#
# Only the latin and latin-ext subsets are kept. latin-ext is not optional --
# the rupee sign U+20B9 lives there, and the calculator is full of it.
#
# Usage:  bin/fetch-fonts.sh
# Output: pub/fonts/*.woff2
#         app/code/EcoLife/Theme/view/base/web/css/fonts.css  (generated)
#
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out_dir="$root/pub/fonts"
css_file="$root/app/code/EcoLife/Theme/view/base/web/css/fonts.css"

# A desktop user agent. Google serves ancient TTFs to anything it does not
# recognise, and we want woff2.
ua='Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36'

query='family=Fraunces:ital,opsz,wght@0,9..144,400..700;1,9..144,400..600'
query+='&family=Manrope:wght@400..800'
query+='&family=IBM+Plex+Mono:wght@400;500'
query+='&display=swap'

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

echo "Fetching font-face declarations from Google Fonts..."
curl -fsS -A "$ua" "https://fonts.googleapis.com/css2?${query}" -o "$tmp/gf.css"

# One record per @font-face block. Emits: family<TAB>style<TAB>weight<TAB>subset<TAB>url
awk 'BEGIN { RS = "}" ; FS = "\n" }
/@font-face/ {
    family = ""; style = ""; weight = ""; url = ""; subset = ""
    for (i = 1; i <= NF; i++) {
        line = $i
        if (line ~ /font-family:/) { family = line; sub(/.*font-family: *./, "", family); sub(/.;.*/, "", family) }
        if (line ~ /font-style:/)  { style  = line; sub(/.*font-style: */, "", style);   sub(/;.*/, "", style) }
        if (line ~ /font-weight:/) { weight = line; sub(/.*font-weight: */, "", weight); sub(/;.*/, "", weight) }
        if (line ~ /src: *url\(/)  { url    = line; sub(/.*url\(/, "", url);             sub(/\).*/, "", url) }
        if (line ~ /unicode-range:/) {
            range = line; sub(/.*unicode-range: */, "", range); sub(/;.*/, "", range)
            if (line ~ /U\+0000-00FF/)      subset = "latin"
            else if (line ~ /U\+0100-02BA/) subset = "latin-ext"
        }
    }
    if (subset != "" && url != "") {
        gsub(/ /, "-", family); gsub(/ /, "-", weight)
        print tolower(family) "\t" style "\t" weight "\t" subset "\t" url "\t" range
    }
}' "$tmp/gf.css" > "$tmp/faces.tsv"

count="$(wc -l < "$tmp/faces.tsv")"
if [ "$count" -eq 0 ]; then
    echo "No latin faces parsed out of the Google Fonts response -- aborting." >&2
    exit 1
fi

mkdir -p "$out_dir"

{
    echo "/*"
    echo " * GENERATED by bin/fetch-fonts.sh -- do not edit by hand."
    echo " *"
    echo " * Self-hosted webfaces, latin and latin-ext subsets only. Imported by"
    echo " * input.css so Tailwind inlines them into the single built stylesheet."
    echo " */"
    echo
} > "$css_file"

while IFS=$'\t' read -r family style weight subset url range; do
    file="${family}-${style}-${weight}-${subset}.woff2"
    if [ ! -f "$out_dir/$file" ]; then
        curl -fsS -A "$ua" "$url" -o "$out_dir/$file"
        printf '  downloaded %-46s %6s KB\n' "$file" "$(( $(stat -c%s "$out_dir/$file") / 1024 ))"
    else
        printf '  cached     %s\n' "$file"
    fi

    # unicode-range is carried through verbatim. It is what tells the browser
    # that U+20B9 -- the rupee sign, which is all over the calculator -- lives
    # in the latin-ext file. Drop it and two faces of the same family/weight
    # collide, the last one wins, and every rupee sign falls back to a system
    # font.
    {
        echo "@font-face {"
        echo "  font-family: '$(echo "$family" | sed -e 's/ibm-plex-mono/IBM Plex Mono/' -e 's/fraunces/Fraunces/' -e 's/manrope/Manrope/')';"
        echo "  font-style: ${style};"
        echo "  font-weight: ${weight//-/ };"
        echo "  font-display: swap;"
        echo "  src: url('/fonts/${file}') format('woff2');"
        echo "  unicode-range: ${range};"
        echo "}"
        echo
    } >> "$css_file"
done < "$tmp/faces.tsv"

echo
echo "Wrote ${count} @font-face rules to ${css_file#"$root"/}"
du -sh "$out_dir" | awk '{print "pub/fonts total: " $1}'
